import { chromium } from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const chrome = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const browser = await chromium.launch({ executablePath: chrome, headless: true, args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader', '--disable-gpu-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
page.setDefaultTimeout(120000);
page.setDefaultNavigationTimeout(180000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  const res = await page.goto('http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' }); assert.equal(res.status(), 200);
  await page.locator('canvas').waitFor({ timeout: 120000 });
  await page.locator('img').evaluateAll(imgs => imgs.forEach(img => { img.loading = 'eager'; }));
  await page.evaluate(() => Promise.all(Array.from(document.images, img => img.decode().catch(() => {}))));
  await page.screenshot({ path: '.review/desktop.png', fullPage: true });
  assert.equal(await page.locator('.project-card').count(), 4);
  await page.getByRole('button', { name: 'Explore all 15 projects' }).click();
  assert.equal(await page.locator('.project-card').count(), 15);
  await page.getByRole('button', { name: 'Civil engineering', exact: true }).click();
  assert.equal(await page.locator('.project-card').count(), 4);
  await page.getByRole('button', { name: 'Automation', exact: true }).click();
  assert.equal(await page.locator('.project-card').count(), 4);
  await page.getByRole('button', { name: 'Explore Stripe → Sheets', exact: true }).click();
  assert.ok(await page.locator('dialog').isVisible());
  assert.equal(await page.locator('dialog video').getAttribute('src'), new URL('/video/stripe google sheet.mp4', page.url()).href);
  await page.keyboard.press('Escape'); assert.equal(await page.locator('dialog').count(), 0);
  await page.getByRole('button', { name: 'Software', exact: true }).click();
  await page.getByRole('button', { name: 'Explore Pipsqueak', exact: true }).click();
  assert.equal(await page.getByRole('link', { name: 'Visit Pipsqueak portal' }).getAttribute('href'), 'https://app.pipsqueaknetscan.com');
  await page.getByRole('button', { name: 'Close project' }).click();
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto('http://127.0.0.1:5173', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Open menu' }).click(); assert.ok(await page.getByRole('navigation').isVisible());
  await page.getByRole('link', { name: 'About 02' }).click(); assert.equal(await page.getByRole('button', { name: 'Open menu' }).getAttribute('aria-expanded'), 'false');
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo({ top: 0, behavior: 'instant' }); });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile horizontal overflow');
  await page.screenshot({ path: '.review/mobile.png', fullPage: true });
  await page.setViewportSize({ width: 320, height: 740 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), '320px horizontal overflow');
  await page.emulateMedia({ reducedMotion: 'reduce' }); await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('h1').waitFor(); assert.ok(await page.locator('h1').isVisible());
  await page.goto('http://127.0.0.1:5173/cv.html', { waitUntil: 'domcontentloaded' });
  await page.emulateMedia({ media: 'print' });
  assert.ok(await page.locator('.page').evaluateAll(pages => pages.every(p => p.scrollHeight <= p.clientHeight + 2)), 'CV page content must fit its print page');
  await page.pdf({ path: 'public/files/Lemi-Fedasa-CV.pdf', format: 'A4', printBackground: true, preferCSSPageSize: true });
  const { getDocument } = await import('pdfjs-dist/legacy/build/pdf.mjs');
  const pdf = await getDocument({ data: new Uint8Array(fs.readFileSync('public/files/Lemi-Fedasa-CV.pdf')) }).promise;
  assert.equal(pdf.numPages, 2, 'CV must be exactly two pages');
  const cvText = (await Promise.all(Array.from({ length: pdf.numPages }, async (_, i) => (await (await pdf.getPage(i + 1)).getTextContent()).items.map(x => x.str).join(' ')))).join(' ');
  for (const term of ['Lemi Fedasa', '2024 onward', 'Pipsqueak', 'Mizan', 'NOVA', 'BENMCON', 'ALX']) assert.ok(cvText.includes(term), `Missing CV text: ${term}`);
  await page.setViewportSize({ width: 900, height: 1200 }); await page.emulateMedia({ media: 'screen' });
  await page.screenshot({ path: '.review/cv.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: desktop, 3D WebGL canvas, 15 projects, category filters, video dialog, Escape, Pipsqueak live link, mobile menu, 390px/320px overflow, reduced motion, CV PDF.');
} finally { await browser.close(); }
